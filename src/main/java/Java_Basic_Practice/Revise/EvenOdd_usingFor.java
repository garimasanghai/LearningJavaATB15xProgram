package Java_Basic_Practice.Revise;

public class EvenOdd_usingFor {
    public static void main(String[] args) {

        for(int i = 1; i<=15; i ++){
            if(i%2 == 0){
                System.out.println(i + " :Even");
            }
            else{
                System.out.println(i);
            }
        }
    }
}
